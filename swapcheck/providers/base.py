"""Base provider abstractions and data structures for LLM calls."""

import json
from abc import ABC, abstractmethod
from typing import Any, Literal

from pydantic import BaseModel, Field


class ToolCall(BaseModel):
    """Represents a tool/function call requested by the LLM."""

    id: str = Field(..., description="Unique tool call invocation ID")
    name: str = Field(..., description="Name of the tool to invoke")
    arguments: dict[str, Any] = Field(
        default_factory=dict, description="Parsed JSON arguments for the tool"
    )

    @classmethod
    def from_raw(cls, call_id: str, name: str, raw_args: str | dict[str, Any]) -> "ToolCall":
        """Construct ToolCall, parsing string arguments if necessary."""
        if isinstance(raw_args, str):
            try:
                parsed = json.loads(raw_args) if raw_args.strip() else {}
            except json.JSONDecodeError:
                parsed = {"__raw_string__": raw_args}
        else:
            parsed = raw_args
        return cls(id=call_id, name=name, arguments=parsed)


class ChatMessage(BaseModel):
    """Normalized chat message structure."""

    role: Literal["system", "user", "assistant", "tool"] = Field(...)
    content: str | None = Field(default=None)
    name: str | None = Field(default=None, description="Tool name for tool responses")
    tool_call_id: str | None = Field(
        default=None, description="Referenced tool call ID when role is tool"
    )
    tool_calls: list[ToolCall] = Field(
        default_factory=list, description="Tool calls issued by assistant"
    )

    def to_dict(self) -> dict[str, Any]:
        """Convert message to dictionary compatible with LLM APIs."""
        d: dict[str, Any] = {"role": self.role}
        if self.content is not None:
            d["content"] = self.content
        if self.name is not None:
            d["name"] = self.name
        if self.tool_call_id is not None:
            d["tool_call_id"] = self.tool_call_id
        if self.tool_calls:
            d["tool_calls"] = [
                {
                    "id": tc.id,
                    "type": "function",
                    "function": {"name": tc.name, "arguments": json.dumps(tc.arguments)},
                }
                for tc in self.tool_calls
            ]
        return d


class TokenUsage(BaseModel):
    """Token consumption for a single completion or trajectory."""

    prompt_tokens: int = Field(0, ge=0)
    completion_tokens: int = Field(0, ge=0)
    total_tokens: int = Field(0, ge=0)


class LLMResponse(BaseModel):
    """Standardized response from an LLM provider."""

    content: str | None = Field(default=None, description="Text content generated by LLM")
    tool_calls: list[ToolCall] = Field(
        default_factory=list, description="List of tool calls requested"
    )
    usage: TokenUsage = Field(default_factory=TokenUsage)
    latency_ms: float = Field(default=0.0, ge=0.0, description="Response latency in milliseconds")
    cost: float = Field(default=0.0, ge=0.0, description="Estimated monetary cost in USD")
    model: str = Field(default="", description="Model identifier used")
    cached: bool = Field(default=False, description="Whether this response was served from cache")


class BaseProvider(ABC):
    """Abstract base class for all LLM providers."""

    def __init__(self, model_name: str, temperature: float = 0.0) -> None:
        self.model_name = model_name
        self.temperature = temperature

    @abstractmethod
    async def complete(
        self,
        messages: list[ChatMessage],
        tools: list[dict[str, Any]] | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        """Generate a response asynchronously given conversation history and optional tools."""
        pass
